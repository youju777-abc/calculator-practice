"""A tiny calculator module for Git practice."""


def add(a, b):
    """Return the sum of two numbers.

    A function is a reusable block of code. Here, `a` and `b` are inputs,
    and the value after `return` is the result.
    """
    return a + b


def subtract(a, b):
    """Return the result of subtracting b from a.

    This function is similar to add(), but it uses the minus operator.
    For example, subtract(5, 2) returns 3.
    """
    return a - b
